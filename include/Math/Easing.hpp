#pragma once

// ==================================================================
//  Easing
//
//  キーフレーム間の補間カーブを表す。正規化された進捗 t (0..1) を
//  受け取り、整形した進捗を返す純関数 ease() を提供する。
// ==================================================================

enum class EasingType {
    Linear,       // 線形
    Quadratic,    // 2次
    Cosine,       // cos
    Sine,         // sin
    Exponential   // 指数
};

// t を [0,1] にクランプしたうえで、種類に応じて整形した進捗を返す
float ease(EasingType type, float t);
